def handle_task_text(uid, text):
    user_states[uid]["task_text"] = text
    user_states[uid]["state"] = "waiting_task_date"

    time_match = None
    for pattern in [r'в\s+(\d{1,2}[:.]\d{2})', r'(\d{1,2}:\d{2})',
                    r'в\s+(\d{1,2})\s*(?:часов|час|ч)']:
        m = re.search(pattern, text.lower())
        if m:
            t = m.group(1)
            if ':' not in t and '.' not in t:
                t = t + ':00'
            else:
                t = t.replace('.', ':')
            time_match = t
            break

    today = datetime.now()
    date_str = today.strftime("%Y-%m-%d")
    tl = text.lower()
    if "послезавтра" in tl:
        date_str = (today + timedelta(days=2)).strftime("%Y-%m-%d")
    elif "завтра" in tl:
        date_str = (today + timedelta(days=1)).strftime("%Y-%m-%d")
    elif "сегодня" in tl:
        date_str = today.strftime("%Y-%m-%d")
    else:
        dm = re.search(r'(\d{1,2})[.\s](\d{1,2})(?:[.\s](\d{2,4}))?', text)
        if dm:
            try:
                d, mo = int(dm.group(1)), int(dm.group(2))
                yr = int(dm.group(3)) if dm.group(3) else today.year
                if yr < 100:
                    yr += 2000
                date_str = datetime(yr, mo, d).strftime("%Y-%m-%d")
            except Exception:
                pass

    user_states[uid]["task_date"] = date_str

    if time_match:
        user_states[uid]["task_time"] = time_match
        finish_task(uid)
    else:
        send(uid,
             f"📅 Дата: {date_str}\n\n"
             "🕐 Укажи время в формате ЧЧ:ММ (например, 14:30)\n"
             "Или напиши «нет», если без времени.\n\n"
             "💡 Чтобы я напомнил за 1 час — обязательно укажи время!")


