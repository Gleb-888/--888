    print("🚀 Бот запущен и слушает сообщения...")

    try:
        for event in longpoll.listen():
            if event.type == VkEventType.MESSAGE_NEW and event.to_me:
                try:
                    uid = event.user_id
                    text = event.text or ""
                    attachments = getattr(event, 'attachments', None) or []
                    handled_media = False

                    for att in attachments:
                        if not isinstance(att, dict):
                            continue
                        att_type = att.get('type')

                        # -------- ФОТО --------
                        if att_type == 'photo':
                            photo = att.get('photo')
                            if isinstance(photo, dict):
                                sizes = photo.get('sizes') or []
                                if sizes:
                                    handled_media = True
                                    largest = max(sizes, key=lambda s: s.get('width', 0) * s.get('height', 0))
                                    url = largest.get('url')
                                    if url:
                                        send(uid, "📷 Распознаю фото...")
                                        try:
                                            img_bytes = urllib.request.urlopen(url, timeout=15).read()
                                            vision_answer = ask_ai_vision(img_bytes)
                                            if vision_answer:
                                                send(uid, f"📷 Ответ по фото:\n\n{vision_answer}", main_kb())
                                            else:
                                                send(uid, "❌ Не удалось распознать фото.")
                                        except Exception as e:
                                            print(f"❌ Ошибка скачивания фото: {e}")
                                            send(uid, "❌ Не удалось скачать фото.")
                                    break

                        # -------- ДОКУМЕНТ-КАРТИНКА --------
                        if att_type == 'doc':
                            doc = att.get('doc')
                            if isinstance(doc, dict):
                                ext = (doc.get('ext') or '').lower()
                                if ext in ('jpg', 'jpeg', 'png', 'gif', 'bmp', 'webp'):
                                    url = doc.get('url')
                                    if url:
                                        handled_media = True
                                        send(uid, "📷 Распознаю изображение...")
                                        try:
                                            img_bytes = urllib.request.urlopen(url, timeout=15).read()
                                            vision_answer = ask_ai_vision(img_bytes)
                                            if vision_answer:
                                                send(uid, f"📷 Ответ по фото:\n\n{vision_answer}", main_kb())
                                            else:
                                                send(uid, "❌ Не удалось распознать.")
                                        except Exception as e:
                                            print(f"❌ Ошибка: {e}")
                                    break

                    if not handled_media:
                        handle_message(uid, text)

                except Exception as e:
                    print(f"❌ Ошибка обработки: {e}")
                    send(event.user_id, "⚠️ Произошла ошибка. Попробуйте ещё раз.")

    except KeyboardInterrupt:
        print("\n👋 Остановка по Ctrl+C")
    except Exception as e:
        print(f"❌ Критическая ошибка: {e}")
    finally:
        reminder.stop()
        print("👋 Бот завершил работу")
