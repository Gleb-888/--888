class ReminderSystem:
    def __init__(self):
        self.running = False

    def start(self):
        self.running = True
        t = threading.Thread(target=self.loop, daemon=True)
        t.start()
        print("🔔 Система напоминаний запущена (за 1 час до события)")

    def stop(self):
        self.running = False

    def loop(self):
        while self.running:
            try:
                now = datetime.now()
                cur_date = now.strftime("%Y-%m-%d")
                cur_hour = now.hour
                cur_min = now.minute

                for uid_str, tasks in list(task_manager.tasks.items()):
                    try:
                        uid = int(uid_str)
                    except Exception:
                        continue
                    for task in tasks:
                        if (task.get("time") and
                                not task.get("reminder_sent") and
                                not task.get("completed") and
                                task.get("date") == cur_date):
                            try:
                                th, tm = map(int, task["time"].split(':'))
                                rh = th - 1
                                rm = tm
                                if rh < 0:
                                    rh += 24
                                if rh == cur_hour and abs(rm - cur_min) <= 1:
                                    text = (
                                        f"⏰ НАПОМИНАНИЕ!\n\n"
                                        f"Через 1 час начинается:\n"
                                        f"📝 {task['text']}\n\n"
                                        f"🕐 Время: {task['time']}\n"
                                        f"📚 Предмет: {task.get('subject') or '—'}\n\n"
                                        f"🎯 Подготовься заранее!\n"
                                        f"💡 Совет: проверь материалы, приготовь тетрадь."
                                    )
                                    send(uid, text)
                                    task["reminder_sent"] = True
                                    task_manager.save()
                                    print(f"📨 Напоминание → {uid}: {task['text'][:30]}")
                            except Exception as e:
                                print(f"⚠️ Ошибка задачи: {e}")
                time.sleep(60)
            except Exception as e:
                print(f"❌ Ошибка напоминаний: {e}")
                time.sleep(60)


