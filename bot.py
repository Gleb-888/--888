class TaskManager:
    def __init__(self):
        self.tasks_file = "vk_tasks.json"
        self.stats_file = "vk_stats.json"
        self.tasks = {}
        self.stats = {}
        self.load()

    def load(self):
        if os.path.exists(self.tasks_file):
            try:
                with open(self.tasks_file, 'r', encoding='utf-8') as f:
                    self.tasks = json.load(f)
            except Exception as e:
                print(f"Ошибка загрузки tasks: {e}")
                self.tasks = {}
        if os.path.exists(self.stats_file):
            try:
                with open(self.stats_file, 'r', encoding='utf-8') as f:
                    self.stats = json.load(f)
            except Exception as e:
                print(f"Ошибка загрузки stats: {e}")
                self.stats = {}

    def save(self):
        try:
            with open(self.tasks_file, 'w', encoding='utf-8') as f:
                json.dump(self.tasks, f, ensure_ascii=False, indent=2)
            with open(self.stats_file, 'w', encoding='utf-8') as f:
                json.dump(self.stats, f, ensure_ascii=False, indent=2)
        except Exception as e:
            print(f"Ошибка сохранения: {e}")

    def add_task(self, user_id, text, date, time_val=None, subject=None):
        uid = str(user_id)
        if uid not in self.tasks:
            self.tasks[uid] = []
        task_id = len(self.tasks[uid]) + 1
        task = {
            "id": task_id,
            "text": text,
            "date": date,
            "time": time_val,
            "subject": subject,
            "created_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "completed": False,
            "reminder_sent": False
        }
        self.tasks[uid].append(task)
        if uid not in self.stats:
            self.stats[uid] = {"total_tasks": 0, "completed_tasks": 0, "last_active": ""}
        self.stats[uid]["total_tasks"] += 1
        self.stats[uid]["last_active"] = datetime.now().strftime("%Y-%m-%d")
        self.save()
        return task

    def get_today(self, user_id):
        today = datetime.now().strftime("%Y-%m-%d")
        return [t for t in self.tasks.get(str(user_id), []) if t["date"] == today]

    def get_week(self, user_id):
        today = datetime.now()
        end = today + timedelta(days=7)
        result = []
        for t in self.tasks.get(str(user_id), []):
            try:
                d = datetime.strptime(t["date"], "%Y-%m-%d")
                if today <= d <= end:
                    result.append(t)
            except Exception:
                continue
        return result

    def get_all(self, user_id):
        return self.tasks.get(str(user_id), [])

    def complete_task(self, user_id, task_id):
        uid = str(user_id)
        for t in self.tasks.get(uid, []):
            if t["id"] == task_id:
                if not t.get("completed"):
                    t["completed"] = True
                    if uid in self.stats:
                        self.stats[uid]["completed_tasks"] = self.stats[uid].get("completed_tasks", 0) + 1
                    self.save()
                return True
        return False

    def delete_task(self, user_id, task_id):
        uid = str(user_id)
        tasks = self.tasks.get(uid, [])
        for i, t in enumerate(tasks):
            if t["id"] == task_id:
                was_done = t.get("completed", False)
                del tasks[i]
                if uid in self.stats:
                    self.stats[uid]["total_tasks"] = len(tasks)
                    if was_done:
                        self.stats[uid]["completed_tasks"] = max(0, self.stats[uid].get("completed_tasks", 0) - 1)
                self.save()
                return True
        return False

    def get_stats(self, user_id):
        uid = str(user_id)
        all_t = self.get_all(user_id)
        total = len(all_t)
        completed = len([t for t in all_t if t.get("completed")])
        rate = (completed / total * 100) if total > 0 else 0
        today_tasks = self.get_today(user_id)
        completed_today = len([t for t in today_tasks if t.get("completed")])
        return {
            "total": total,
            "completed": completed,
            "rate": rate,
            "today": len(today_tasks),
            "today_done": completed_today,
            "week": len(self.get_week(user_id)),
            "last_active": self.stats.get(uid, {}).get("last_active", "—")
        }


